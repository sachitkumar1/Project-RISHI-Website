#!/usr/bin/env python3
"""
Regenerate lib/imagePlaceholders.ts — a tiny blurred preview plus the exact
width/height of every photo under public/images/.

Run it after adding or replacing a photo:
    pip install Pillow
    python3 scripts/gen-image-placeholders.py

Why this exists: the site shows the preview at the photo's real size while the
full photo downloads, so nothing jumps and there is never an empty box. The
previews are ~16px WebP images (about 150 bytes each); browsers smooth them
into a blur when stretched. A photo missing from the file still works — it just
loads without a preview.

Sizes are measured after EXIF rotation, because browsers display phone photos
rotated the way the camera recorded them.
"""
import base64
import io
import json
import pathlib

from PIL import Image, ImageOps

ROOT = pathlib.Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public"
OUT = ROOT / "lib" / "imagePlaceholders.ts"
PHOTO_EXT = {".jpg", ".jpeg", ".webp"}  # logos (PNG) are left alone
MAX_SIDE = 16

entries = {}
for path in sorted((PUBLIC / "images").rglob("*")):
    if path.suffix.lower() not in PHOTO_EXT:
        continue
    with Image.open(path) as im:
        im = ImageOps.exif_transpose(im).convert("RGB")
        w, h = im.size
        thumb = im.copy()
        thumb.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
        buf = io.BytesIO()
        thumb.save(buf, "WEBP", quality=60, method=6)
    key = "/" + path.relative_to(PUBLIC).as_posix()
    entries[key] = {
        "w": w,
        "h": h,
        "blur": "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode(),
    }

lines = [
    "// GENERATED by scripts/gen-image-placeholders.py — do not edit by hand.",
    "// Re-run that script after adding or replacing a photo in public/images/.",
    "",
    "export type ImagePlaceholder = { w: number; h: number; blur: string };",
    "",
    "export const IMAGE_PLACEHOLDERS: Record<string, ImagePlaceholder> = {",
]
for key, v in entries.items():
    lines.append(f"  {json.dumps(key)}: {{ w: {v['w']}, h: {v['h']}, blur: {json.dumps(v['blur'])} }},")
lines += [
    "};",
    "",
    "/** The preview for a site photo, or undefined for anything else (uploads, external URLs). */",
    "export function placeholderFor(src: string | null | undefined): ImagePlaceholder | undefined {",
    "  return src ? IMAGE_PLACEHOLDERS[src] : undefined;",
    "}",
    "",
    "/** Style that paints the preview behind a plain <img>; the photo covers it once loaded. */",
    "export function blurBehind(src: string | null | undefined, position = \"center\"): { backgroundImage?: string; backgroundSize?: string; backgroundPosition?: string } {",
    "  const p = placeholderFor(src);",
    "  return p ? { backgroundImage: `url(\"${p.blur}\")`, backgroundSize: \"cover\", backgroundPosition: position } : {};",
    "}",
    "",
]
OUT.write_text("\n".join(lines))
total = sum(len(v["blur"]) for v in entries.values())
print(f"{len(entries)} photos -> {OUT.relative_to(ROOT)} ({total} bytes of previews)")
